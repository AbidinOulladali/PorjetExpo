// Hook pratique pour récupérer les textes selon la langue active ('fr' | 'en' | 'ar')
export function useTraduction(langue = 'fr') {
  const estArabe = langue === 'ar';
  const t = useMemo(
    () => TRADUCTIONS[langue] || TRADUCTIONS.fr,
    [langue]
  );

  return {
    langue,
    estArabe,
    t,
  };
}